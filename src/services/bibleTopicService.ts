import { bibleTopics, mockStudyContent } from "../data/bibleTopics";
import type {
  BibleTopic,
  TopicStudyRequest,
  TopicStudyResult,
  TranslationId,
} from "../types/bible";

const delay = (ms: number) => new Promise((r) => setTimeout(r, ms));

export const bibleTopicService = {
  /** Free: search topics by title, alias, or verse reference. */
  async search(query: string): Promise<BibleTopic[]> {
    await delay(180);
    const q = query.trim().toLowerCase();
    if (!q) return bibleTopics;

    return bibleTopics.filter(
      (t) =>
        t.title.toLowerCase().includes(q) ||
        t.summary.toLowerCase().includes(q) ||
        t.aliases.some((a) => a.includes(q)) ||
        t.verses.some((v) => v.reference.toLowerCase().includes(q))
    );
  },

  /** Free: get a single topic with its free-tier verses. */
  async getTopic(id: string): Promise<BibleTopic | null> {
    await delay(120);
    return bibleTopics.find((t) => t.id === id) ?? null;
  },

  /** Free: get verses for a topic in a specific translation. */
  async getTopicVerses(
    topicId: string,
    translation: TranslationId
  ): Promise<BibleTopic["verses"]> {
    await delay(150);
    const topic = bibleTopics.find((t) => t.id === topicId);
    if (!topic) return [];
    // In real backend: fetch from your stored Bible DB filtered by translation
    return topic.verses.map((v) => ({ ...v, translation }));
  },

  /**
   * PAID: AI deep-dive study.
   * In production this hits POST /api/ai/topic-study and streams.
   * Here it returns mock content after a delay.
   */
  async generateStudy(
    request: TopicStudyRequest
  ): Promise<TopicStudyResult> {
    await delay(1200);
    const base = mockStudyContent[request.topicId];
    if (base) return { ...base, focus: request.focus };

    // Generic fallback for topics without mock content
    const topic = bibleTopics.find((t) => t.id === request.topicId);
    return {
      topicId: request.topicId,
      focus: request.focus,
      sections: [
        {
          heading: "Overview",
          body: `A deep study of ${topic?.title ?? "this topic"} would appear here, generated by the AI from your stored Bible corpus and cross-reference data.`,
        },
      ],
      crossReferences: topic?.verses.map((v) => ({
        reference: v.reference,
        text: v.text,
      })) ?? [],
      generatedAt: new Date().toISOString(),
    };
  },
};